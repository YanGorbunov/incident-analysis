-- Счётчики кодов для справочников, заполненных выше
INSERT INTO code_counter (scope, prefix, last_value)
SELECT 'DEPARTMENT', '', max(code::int) FROM department
UNION ALL SELECT 'POST', split_part(code, '.', 1), max(split_part(code, '.', 2)::int) FROM post GROUP BY 2
UNION ALL SELECT 'PRIORITY', '', max(code::int) FROM priority
UNION ALL SELECT 'STATUS', '', max(code::int) FROM status
UNION ALL SELECT 'CI_TYPE', '', max(code::int) FROM ci_type;
